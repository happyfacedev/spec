// index.md: modules by domain, one line per feature. Generated and committed; never edited by hand.
// It holds nothing that changes with every edit (no version hash, no line numbers), so it changes
// in a PR only when a module or a feature's title or status does.
import { compareIds, compareStrings } from './ids';
import type { Spec } from './model';

export const GRAPH_PATH = '_generated/graph.json';
export const INDEX_PATH = 'index.md';

export function renderIndex(spec: Spec): string {
  const lines: string[] = [];
  lines.push(`# ${spec.skillName ?? 'Spec'} index`, '');
  lines.push('Generated by `spec build`. Do not edit; run `spec show <ID>` for any line.', '');
  const domains = [...new Set(spec.modules.map((m) => m.domain))].sort(compareStrings);
  for (const domain of domains) {
    lines.push(`## ${domain}`, '');
    for (const m of spec.modules.filter((x) => x.domain === domain).sort((a, b) => compareIds(a.id, b.id))) {
      const first = m.responsibility.split(/(?<=\.)\s/)[0]?.trim() ?? '';
      lines.push(`### ${m.id} · ${m.prefix}${m.status !== 'active' ? ` (${m.status})` : ''}`);
      if (first) lines.push(first);
      const fs = spec.features.filter((f) => f.module === m.id);
      if (fs.length > 0) lines.push('');
      for (const f of fs) {
        const dep = f.status !== 'active' ? ` (${f.status}${f.supersededBy ? ` → ${f.supersededBy.id}` : ''})` : '';
        lines.push(`- ${f.id} ${f.title}${dep}`);
      }
      lines.push('');
    }
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}
