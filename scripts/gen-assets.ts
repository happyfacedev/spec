// Embeds roles/ and templates/ into src/generated/assets.ts, so dist/spec needs no files beside it.
//   npx tsx scripts/gen-assets.ts          write
//   npx tsx scripts/gen-assets.ts --check  exit 1 when stale (tests run the same check)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const REPO = join(import.meta.dirname, '..');
export const ASSETS_PATH = join(REPO, 'src/generated/assets.ts');

function files(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((n) => (statSync(join(dir, n)).isDirectory() ? files(join(dir, n)) : [join(dir, n)]));
}

export function renderAssets(): string {
  const templates = files(join(REPO, 'templates'));
  const entries = [...files(join(REPO, 'roles')), ...templates].map((f) => [relative(REPO, f).split('\\').join('/'), readFileSync(f, 'utf8')] as const);
  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  return `// Generated by scripts/gen-assets.ts from roles/ and templates/. Do not edit.\nexport const ASSETS: Readonly<Record<string, string>> = {\n${body}\n};\n`;
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const want = renderAssets();
  if (process.argv.includes('--check')) {
    const have = readFileSync(ASSETS_PATH, 'utf8');
    if (have !== want) {
      process.stderr.write('src/generated/assets.ts is stale: run npx tsx scripts/gen-assets.ts\n');
      process.exit(1);
    }
  } else writeFileSync(ASSETS_PATH, want);
}
