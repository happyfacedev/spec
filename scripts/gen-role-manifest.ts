// The shipped-prompt manifest (INS-005/R5): for every version of spec, the sha256 of each stage-role
// prompt as `spec init` installs it (expanded). Hooks and `spec verify-history` accept a role-update
// commit only when its files are listed here, so entries are only ever added, never pruned or edited.
//   npx tsx scripts/gen-role-manifest.ts          add the current version's hashes
//   npx tsx scripts/gen-role-manifest.ts --check  exit 1 when they are missing (lint runs the same check)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expandRole } from '../src/core/roles';
import { ROLES } from '../src/core/schemas';
import { ROLE_MANIFEST } from '../src/generated/role-manifest';

const REPO = join(import.meta.dirname, '..');
export const MANIFEST_PATH = join(REPO, 'src/generated/role-manifest.ts');

type Manifest = Readonly<Record<string, Readonly<Record<string, readonly string[]>>>>;

const sha256 = (text: string): string => createHash('sha256').update(text, 'utf8').digest('hex');

function currentVersion(): string {
  const pkg: unknown = JSON.parse(readFileSync(join(REPO, 'package.json'), 'utf8'));
  const version = (pkg as { version?: unknown }).version;
  if (typeof version !== 'string') throw new Error('package.json has no version');
  return version;
}

/** The hash of each stage-role prompt this checkout ships, as `spec init` installs it. */
export function shippedHashes(): Record<string, string> {
  const shared = readFileSync(join(REPO, 'roles/_shared.md'), 'utf8');
  const hashes: Record<string, string> = {};
  for (const role of [...ROLES].sort()) {
    const text = expandRole(readFileSync(join(REPO, `roles/${role}.md`), 'utf8'), shared);
    if (text === null) throw new Error(`roles/${role}.md does not parse`);
    hashes[role] = sha256(text);
  }
  return hashes;
}

/** The manifest with this version's hashes added; every earlier entry is kept as it is. */
export function withCurrent(existing: Manifest, version: string, hashes: Readonly<Record<string, string>>): Manifest {
  const entry: Record<string, readonly string[]> = { ...existing[version] };
  for (const [role, hash] of Object.entries(hashes)) {
    const known = entry[role] ?? [];
    if (!known.includes(hash)) entry[role] = [...known, hash];
  }
  return { ...existing, [version]: entry };
}

export function renderManifest(manifest: Manifest): string {
  const versions = Object.entries(manifest).map(([version, roles]) => {
    const body = Object.entries(roles)
      .map(([role, hashes]) => `    ${JSON.stringify(role)}: [${hashes.map((h) => JSON.stringify(h)).join(', ')}],`)
      .join('\n');
    return `  ${JSON.stringify(version)}: {\n${body}\n  },`;
  });
  return `// Generated by scripts/gen-role-manifest.ts. Do not edit: versions are only ever added, never removed.\n// Per version of spec and stage role, the sha256 of each prompt that version shipped, as \`spec init\` installs it.\nexport const ROLE_MANIFEST: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = {\n${versions.join('\n')}\n};\n`;
}

export function wantedManifest(): string {
  return renderManifest(withCurrent(ROLE_MANIFEST, currentVersion(), shippedHashes()));
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const want = wantedManifest();
  if (process.argv.includes('--check')) {
    if (readFileSync(MANIFEST_PATH, 'utf8') !== want) {
      process.stderr.write('src/generated/role-manifest.ts lacks this version\'s role prompts: run npx tsx scripts/gen-role-manifest.ts\n');
      process.exit(1);
    }
  } else writeFileSync(MANIFEST_PATH, want);
}
